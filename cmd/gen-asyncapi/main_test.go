package main

import (
	"bytes"
	"context"
	"os"
	"path/filepath"
	"testing"

	"github.com/psyb0t/ctxerrors/commerr"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func shapesSpec(t *testing.T) string {
	t.Helper()

	path, err := filepath.Abs(
		filepath.Join("..", "..", "examples", "shapes", "shapes.yaml"),
	)
	require.NoError(t, err)

	return path
}

func TestRunWithConfig(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	output := filepath.Join(dir, "out.gen.go")
	configPath := filepath.Join(dir, "config.yaml")
	config := "package: shapes\noutput: " + output +
		"\ngenerate:\n  models: true\n"
	require.NoError(t, os.WriteFile(configPath, []byte(config), 0o600))

	require.NoError(
		t,
		run(
			context.Background(),
			[]string{"--config=" + configPath, shapesSpec(t)},
			&bytes.Buffer{},
		),
	)

	generated, err := os.ReadFile(output)
	require.NoError(t, err)
	assert.Contains(t, string(generated), "package shapes")
	assert.Contains(t, string(generated), "type Node struct")
	assert.NotContains(
		t,
		string(generated),
		"type Client struct",
		"models only leaves the client out",
	)
}

func TestRunWithFlagsOnly(t *testing.T) {
	t.Parallel()

	output := filepath.Join(t.TempDir(), "flags.gen.go")

	require.NoError(
		t,
		run(
			context.Background(),
			[]string{"-package=feed", "-o=" + output, shapesSpec(t)},
			&bytes.Buffer{},
		),
	)

	generated, err := os.ReadFile(output)
	require.NoError(t, err)
	assert.Contains(t, string(generated), "package feed")
	assert.Contains(
		t,
		string(generated),
		"type Client struct",
		"everything is generated by default",
	)
}

func TestRunTypeScript(t *testing.T) {
	t.Parallel()

	output := filepath.Join(t.TempDir(), "shapes.gen.ts")

	require.NoError(
		t,
		run(
			context.Background(),
			[]string{"-language=typescript", "-o=" + output, shapesSpec(t)},
			&bytes.Buffer{},
		),
	)

	generated, err := os.ReadFile(output)
	require.NoError(t, err)
	assert.Contains(t, string(generated), "export interface Node {")
	assert.Contains(t, string(generated), "export class Client {")

	require.ErrorIs(
		t,
		run(
			context.Background(),
			[]string{"-language=rust", "-o=" + output, shapesSpec(t)},
			&bytes.Buffer{},
		),
		commerr.ErrInvalidValue,
	)
}

func TestRunErrors(t *testing.T) {
	t.Parallel()

	usage := &bytes.Buffer{}
	require.Error(t, run(context.Background(), []string{"-nope"}, usage))
	assert.Contains(t, usage.String(), "-config")

	usage.Reset()
	require.ErrorIs(
		t,
		run(context.Background(), []string{"-package=x"}, usage),
		commerr.ErrInvalidArgument,
	)
	assert.Contains(t, usage.String(), "usage: gen-asyncapi")

	err := run(
		context.Background(),
		[]string{
			"--config=" + filepath.Join(t.TempDir(), "missing.yaml"),
			"x.yaml",
		},
		&bytes.Buffer{},
	)
	require.ErrorIs(t, err, os.ErrNotExist)

	require.ErrorIs(
		t,
		run(context.Background(), []string{shapesSpec(t)}, &bytes.Buffer{}),
		commerr.ErrRequiredConfigValueNotSet,
	)

	output := filepath.Join(t.TempDir(), "x.gen.go")
	err = run(
		context.Background(),
		[]string{
			"-package=x",
			"-o=" + output,
			filepath.Join(t.TempDir(), "missing.yaml"),
		},
		&bytes.Buffer{},
	)
	require.ErrorIs(t, err, os.ErrNotExist)
}
